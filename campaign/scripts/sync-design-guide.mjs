#!/usr/bin/env node
// Keeps docs/design-guide.md in step with the code.
//
//   node scripts/sync-design-guide.mjs          rewrite the generated token table in the guide
//   node scripts/sync-design-guide.mjs --check  exit 1 if the guide's table is out of date (used by CI)
//
// The table between <!-- tokens:start --> and <!-- tokens:end --> is generated from the CSS custom
// properties in campaign/index.html (light :root block and :root[data-theme="dark"] block). Edit the
// colors in the page, never in the table.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const repo = new URL("..", import.meta.url).pathname;
const page = readFileSync(join(repo, "index.html"), "utf8");
const guidePath = join(repo, "docs/design-guide.md");
const guide = readFileSync(guidePath, "utf8");

const block = (re) => { const m = page.match(re); if (!m) throw new Error(`token block not found: ${re}`); return m[1]; };
const vars = (css) => Object.fromEntries([...css.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]));
const light = vars(block(/:root\{([^}]*)\}/));
const dark = vars(block(/:root\[data-theme="dark"\]\{([^}]*)\}/));

const skip = new Set(["--display", "--body", "--mono"]);
const keys = [...new Set([...Object.keys(dark), ...Object.keys(light)])].filter((k) => !skip.has(k));
const cell = (v) => (v ? "`" + v + "`" : "—");
const rows = keys.map((k) => `| \`${k}\` | ${cell(dark[k])} | ${cell(light[k])} |`);
const fonts = ["--display", "--body", "--mono"].map((k) => `| \`${k}\` | ${light[k] ?? "—"} |`);

const table = [
  "<!-- tokens:start — generated by scripts/sync-design-guide.mjs from campaign/index.html; do not edit by hand -->",
  "| Token | Dark (default) | Light |",
  "| --- | --- | --- |",
  ...rows,
  "",
  "| Font token | Stack |",
  "| --- | --- |",
  ...fonts,
  "<!-- tokens:end -->",
].join("\n");

const re = /<!-- tokens:start[\s\S]*?<!-- tokens:end -->/;
if (!re.test(guide)) { console.error("docs/design-guide.md has no <!-- tokens:start --> … <!-- tokens:end --> block"); process.exit(1); }
const next = guide.replace(re, table);

if (process.argv.includes("--check")) {
  if (next !== guide) {
    console.error("✗ docs/design-guide.md token table is out of date. Run: node scripts/sync-design-guide.mjs");
    process.exit(1);
  }
  console.log(`✓ design guide tokens match campaign/index.html (${keys.length} tokens)`);
} else {
  writeFileSync(guidePath, next);
  console.log(`docs/design-guide.md: token table ${next === guide ? "already current" : "updated"} (${keys.length} tokens)`);
}
